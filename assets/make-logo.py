"""
Generates the Keylo logo (src/Keylo.App/Assets/Logo.xaml and assets/keylo.svg) from one set of
points, so the two never drift. Then run make-icon.ps1 to render the PNGs and keylo.ico.

The mark is a faceted "K": a hexagon with a notch cut into its right side, and a separate chevron
sitting in the notch. Each piece is a rounded polygon filled with flat facets (triangles from a
common point) in violet tones, like cut glass.
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# --- geometry, on a 256x256 grid --------------------------------------------------------------
# Body: flat-topped hexagon whose right side is notched in to N.
P_LEFT, P_TL, P_TR, N, P_BR, P_BL = (12, 128), (62, 40), (170, 40), (124, 128), (170, 216), (62, 216)
BODY = [P_LEFT, P_TL, P_TR, N, P_BR, P_BL]

# Chevron: its left edges run parallel to the notch, GAP units away.
GAP = 20
def along(p, q, y):
    """Point on the line p->q at height y."""
    t = (y - p[1]) / (q[1] - p[1])
    return (p[0] + t * (q[0] - p[0]), y)

tip = (N[0] + GAP * 1.1, 128)
up_dir = (P_TR[0] - N[0], P_TR[1] - N[1])
down_dir = (P_BR[0] - N[0], P_BR[1] - N[1])
c_top = along(tip, (tip[0] + up_dir[0], tip[1] + up_dir[1]), 66)
c_bot = along(tip, (tip[0] + down_dir[0], tip[1] + down_dir[1]), 190)
CHEVRON = [tip, c_top, (236, 96), (236, 160), c_bot]

# Facets: triangles fanning from a point inside each piece.
BODY_CENTER = (84, 118)
BODY_FACETS = [  # (corner a, corner b, colour)
    (P_BL, P_LEFT, "#9333EA"),
    (P_LEFT, P_TL, "#A855F7"),
    (P_TL, P_TR, "#8B5CF6"),
    (P_TR, N, "#6D28D9"),
    (N, P_BR, "#7C3AED"),
    (P_BR, P_BL, "#5B21B6"),
]
# Fanned from the tip: light on top, deeper below, like light from the upper left.
CHEVRON_CENTER = tip
CHEVRON_FACETS = [
    (CHEVRON[1], CHEVRON[2], "#DDD6FE"),
    (CHEVRON[2], CHEVRON[3], "#A78BFA"),
    (CHEVRON[3], CHEVRON[4], "#7C3AED"),
]
RADIUS = 14


def rounded(points, r):
    """Path data for a closed polygon with corners rounded by quadratic curves."""
    out = []
    n = len(points)
    for i in range(n):
        prev, cur, nxt = points[i - 1], points[i], points[(i + 1) % n]
        def toward(a, b, d):
            dx, dy = b[0] - a[0], b[1] - a[1]
            length = math.hypot(dx, dy)
            d = min(d, length / 2.5)
            return (a[0] + dx / length * d, a[1] + dy / length * d)
        start, end = toward(cur, prev, r), toward(cur, nxt, r)
        out.append(("M" if i == 0 else "L") + f"{start[0]:.1f},{start[1]:.1f} Q{cur[0]:.1f},{cur[1]:.1f} {end[0]:.1f},{end[1]:.1f}")
    return " ".join(out) + " Z"


def poly(points):
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in points) + " Z"


def facets(center, spec):
    return [(poly([center, a, b]), colour) for a, b, colour in spec]


body_outline = rounded(BODY, RADIUS)
chevron_outline = rounded(CHEVRON, RADIUS * 0.7)
pieces = [(body_outline, facets(BODY_CENTER, BODY_FACETS)), (chevron_outline, facets(CHEVRON_CENTER, CHEVRON_FACETS))]

# --- XAML --------------------------------------------------------------------------------------
xaml_groups = []
for outline, fs in pieces:
    drawings = "\n".join(
        f'                        <GeometryDrawing Brush="{c}" Geometry="{d}" />' for d, c in fs)
    xaml_groups.append(f'''                    <DrawingGroup ClipGeometry="{outline}">
{drawings}
                        <GeometryDrawing Brush="{{StaticResource LogoSheenBrush}}" Geometry="{outline}" />
                    </DrawingGroup>''')

xaml = f'''<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">

    <!--
        Keylo logo on a 256x256 grid: a faceted "K" made of a notched hexagon and a chevron.
        GENERATED by assets/make-logo.py (which also writes assets/keylo.svg); edit that instead.
    -->

    <LinearGradientBrush x:Key="LogoSheenBrush" StartPoint="0,0" EndPoint="1,1">
        <GradientStop Color="#33FFFFFF" Offset="0" />
        <GradientStop Color="#00FFFFFF" Offset="0.5" />
        <GradientStop Color="#1A1E1B4B" Offset="1" />
    </LinearGradientBrush>

    <DrawingImage x:Key="LogoImage">
        <DrawingImage.Drawing>
            <DrawingGroup>
                <!-- Transparent square so the image keeps its 256x256 bounds. -->
                <GeometryDrawing Brush="Transparent" Geometry="M0,0 H256 V256 H0 Z" />
{chr(10).join(xaml_groups)}
            </DrawingGroup>
        </DrawingImage.Drawing>
    </DrawingImage>
</ResourceDictionary>
'''
open(os.path.join(ROOT, "src", "Keylo.App", "Assets", "Logo.xaml"), "w", encoding="utf-8").write(xaml)

# --- SVG ---------------------------------------------------------------------------------------
svg_groups = []
for i, (outline, fs) in enumerate(pieces):
    paths = "\n".join(f'    <path fill="{c}" d="{d}"/>' for d, c in fs)
    svg_groups.append(f'''  <clipPath id="piece{i}"><path d="{outline}"/></clipPath>
  <g clip-path="url(#piece{i})">
{paths}
    <path fill="url(#sheen)" d="{outline}"/>
  </g>''')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">
  <!-- Keylo logo. GENERATED by assets/make-logo.py (also writes src/Keylo.App/Assets/Logo.xaml). -->
  <defs>
    <linearGradient id="sheen" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.2"/>
      <stop offset="0.5" stop-color="#fff" stop-opacity="0"/>
      <stop offset="1" stop-color="#1E1B4B" stop-opacity="0.1"/>
    </linearGradient>
  </defs>
{chr(10).join(svg_groups)}
</svg>
'''
open(os.path.join(ROOT, "assets", "keylo.svg"), "w", encoding="utf-8").write(svg)
print("wrote Logo.xaml and keylo.svg")
